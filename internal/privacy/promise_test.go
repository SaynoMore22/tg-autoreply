package privacy

import "testing"

func TestCommitment(t *testing.T) {
	for _, s := range []string{
		"ждите, сейчас приеду",
		"да, приду",
		"в 9?",
		"давай в 19:30",
		"буду через час",
		"через пару минут",
		"скину вечером",
		"ок, займу",
		"договорились",
		"подожди, выхожу",
		"переведу завтра",
	} {
		if !Commitment(s) {
			t.Errorf("обещание не распознано: %q", s)
		}
	}
	for _, s := range []string{
		"ахах ору",
		"норм, ты как",
		"мб, ближе к вечеру напишу",
		"хз, посмотрим",
		"да так, дома сижу",
		"ну го как-нибудь",
		"ищу работу",
		"в субботу хз",
		"в 2026 году", // год, а не время
		"ждун",
	} {
		if Commitment(s) {
			t.Errorf("ложное срабатывание: %q", s)
		}
	}
}
