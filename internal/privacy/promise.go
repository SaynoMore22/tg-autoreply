package privacy

import "regexp"

// Обещания и конкретика, которые бот не вправе давать за владельца:
// приеду/приду/скину/переведу, «в 9», «через час», «договорились».
var promises = []*regexp.Regexp{
	regexp.MustCompile(`(?:^|\P{L})(приеду|приедем|приду|придём|придем|подъеду|подойду|заеду|зайду|выезжаю|выхожу|еду|буду\s+(в|через|к|у|на\s+месте)|скину|скинул|переведу|перевёл|перевел|отправлю|займу|одолжу|верну|куплю|оплачу|договорились|забились|жди|ждите|подожди|подождите)(?:\P{L}|$)`),
	regexp.MustCompile(`(?:^|\P{L})(в|к|до|после)\s+\d{1,2}([:.]\d{2})?(?:[^\p{L}\d]|$)`),
	regexp.MustCompile(`(?:^|\P{L})через\s+(\d+|пару|полчаса|час|минут\p{L}*|полтора)(?:\P{L}|$)`),
	regexp.MustCompile(`(?:^|\P{L})(да|ага|ок|окей|конечно),?\s+(приду|буду|иду|заеду|скину|займу|давай\s+в)(?:\P{L}|$)`),
}

// Commitment — есть ли в ответе обещание или конкретное время за владельца.
func Commitment(s string) bool {
	c := Canon(s)
	for _, re := range promises {
		if re.MatchString(c) {
			return true
		}
	}
	return false
}
