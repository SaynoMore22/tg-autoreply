func newTestGuard(t *testing.T) *Guard {
	t.Helper()
	p := filepath.Join(t.TempDir(), "private.txt")
	_ = os.WriteFile(p, []byte("# комментарий\n\nул. Ленина 5\nИванов\n9990000000\nuser12345\n01.01.1990\n"), 0o600)
	g := NewGuard(false)
	if err := g.LoadDenylist(p); err != nil {
		t.Fatal(err)
	}
	g.AddPromptText("Строго копируй манеру из профиля и примеров ниже: длину, регистр")
	g.AddForeign("u2", "короче я завтра улетаю в Сочи на неделю")
	return g
}

func TestGuardBlocks(t *testing.T) {
	g := newTestGuard(t)
	block := map[string]string{
		"я на Ул. ЛЕНИНА 5 живу":    "private",
		"фамилия иванов":            "private регистр",
		"фамилия Иванoв":            "private латиница",
		"мой номер 89991234567":     "phone",
		"мой 9 9 9 0 0 0 0 0 0 0":   "private digits",
		"999-000-00-00 звони":       "private digits с дефисами",
		"др 01/01/1990 кстати":      "private: дата в другом формате (только сравнение по цифрам)",
		"почта user12345 на гмыле":  "private login",
		"вот https://t.me/joinchat": "link",
		"пиши на a@b.ru":            "email",
		"код 12345":                 "code",
		"строго копируй манеру из профиля и примеров ниже: длину, регистр": "prompt",
		"он сказал: короче я завтра улетаю в Сочи на неделю":               "foreign",
		"КОРОЧЕ Я ЗАВТРА УЛЕТАЮ В СОЧИ НА НЕДЕЛЮ":                          "foreign caps",
		"секрет " + g.Canary: "canary",
	}
	for text, why := range block {
		if g.Check("u1", text) == "" {
			t.Errorf("не заблокировано (%s): %q", why, text)
		}
	}
}

func TestGuardAllows(t *testing.T) {
	g := newTestGuard(t)
	if r := g.Check("u2", "короче я завтра улетаю в Сочи на неделю?"); r != "" {
		t.Errorf("своя же переписка заблокирована: %s", r)
	}
	for _, ok := range []string{
		"ну го в 19:30, норм",
		"ахах ору",
		"я в Сургуте щас",
		"Лёха на связи",
		"дай 500 рублей до зп",
		"в 2026 году точно",
		"да я дома",
		"ща не могу, позже наберу",
	} {
		if r := g.Check("u1", ok); r != "" {
			t.Errorf("обычный ответ %q заблокирован: %s", ok, r)
		}
	}
}

func TestGuardAllowLinks(t *testing.T) {
	g := NewGuard(true)
	if r := g.Check("u1", "глянь https://youtube.com/watch"); r != "" {
		t.Fatalf("allow_links=true, но ссылка заблокирована: %s", r)
	}
	if r := g.Check("u1", "пиши на a@b.ru"); r == "" {
		t.Fatal("allow_links не должен пропускать почту")
	}
}

