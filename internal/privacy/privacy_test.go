func TestRedact(t *testing.T) {
	cases := map[string]string{
		"звони +7 (999) 123-45-67":                          "звони [телефон]",
		"звони 8 999 123 45 67":                             "звони [телефон]",
		"пиши на ivan.petrov@mail.ru":                       "пиши на [почта]",
		"почта вася@почта.рф":                               "почта [почта]",
		"карта 4276 1234 5678 9012":                         "карта [номер карты]",
		"карта 4276-1234-5678-9012":                         "карта [номер карты]",
		"код 48213":                                         "код [код или номер]",
		"глянь https://example.com/x?y=1":                   "глянь [ссылка]",
		"вот t.me/somechannel":                              "вот [ссылка]",
		"кошель 0x52908400098527886E0F7030069857D2E4169EE7": "кошель [кошелёк]",
		"ну го в 19:30":                                     "ну го в 19:30",
		"дай 500 рублей":                                    "дай 500 рублей",
		"в 2026 году":                                       "в 2026 году",
		"счёт 3:1 в нашу пользу":                            "счёт 3:1 в нашу пользу",
	}
	for in, want := range cases {
		if got := Redact(in); got != want {
			t.Errorf("Redact(%q) = %q, want %q", in, got, want)
		}
	}
}

